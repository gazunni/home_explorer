const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const js=fs.readFileSync('home_explorer/web/app.js','utf8');
const html=fs.readFileSync('home_explorer/web/index.html','utf8');
const start=js.indexOf('const equipmentPageSize = 8;');
const end=js.indexOf('function render() {',start);
assert.ok(start>=0 && end>start);
const ctx={}; vm.createContext(ctx);
vm.runInContext(js.slice(start,end),ctx);
const items=Array.from({length:140},(_,i)=>i);
assert.equal(ctx.paginateEquipment(items,0).items.length,8);
assert.equal(ctx.paginateEquipment(items,0).pages,18);
assert.equal(ctx.paginateEquipment(items,1).items[0],8);
assert.equal(ctx.paginateEquipment(items,17).items.length,4);
assert.equal(ctx.paginateEquipment(items,99).index,17);
assert.equal(ctx.paginateEquipment(items,-2).index,0);
assert.equal(ctx.paginateEquipment([],0).items.length,0);
assert.equal(ctx.paginateEquipment([1,2,3],15).index,0);
assert.ok(js.includes("equipmentPage=0; render();"));
assert.ok(html.includes('id="equipment-prev"'));
assert.ok(html.includes('id="equipment-next"'));
assert.ok(html.includes('id="equipment-page-status"'));
console.log('Equipment pagination regression tests passed');
